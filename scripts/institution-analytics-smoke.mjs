import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const exists = (file) => fs.existsSync(path.join(root, file));
const checks = [];
const check = (label, ok) => checks.push({ label, ok: Boolean(ok) });

const pkg = JSON.parse(read('package.json'));
const types = read('src/types/institution-analytics.ts');
const route = read('src/app/api/institution-analytics/route.ts');
const reports = read('src/lib/institutionReportPdf.ts');
const workspace = read('src/components/institution-analytics/institution-analytics-workspace.tsx');
const institutionCss = read('src/components/institution-analytics/institution-analytics.css');
const studentAnalytics = read('src/components/analytics-v12/student-analytics-v12.tsx');
const studentCss = read('src/components/analytics-v12/analytics-v12.css');
const store = read('src/store/use-app-store.ts');
const views = read('src/lib/workspaceViews.ts');
const sidebar = read('src/components/evidara/app-sidebar.tsx');
const page = read('src/app/page.tsx');
const questions = read('src/components/evidara/live-question-bank.tsx');
const tsconfig = JSON.parse(read('tsconfig.json'));

check('package is current Evidara V19', pkg.name === 'evidara-school-platform' && pkg.version === '19.1.0');
check('institution analytics API exists', exists('src/app/api/institution-analytics/route.ts'));
check('institution analytics workspace exists', exists('src/components/institution-analytics/institution-analytics-workspace.tsx'));
check('report-card generator exists', exists('src/lib/institutionReportPdf.ts'));
check('hardcoded institution demonstration source is removed', !exists('src/lib/institutionAnalyticsDemo.ts'));
check('workspace has no institution demo import', !workspace.includes('institutionAnalyticsDemo') && !workspace.includes('demonstrationFallback'));
check('known fake St Marys section ID is absent', !route.includes('st-marys-isc-g11-science-a') && !workspace.includes('st-marys-isc-g11-science-a'));
check('all drill-down levels are typed', ['schools', 'school', 'class', 'subject', 'chapter', 'student'].every((value) => types.includes(`'${value}'`)));
check('school rows expose live organization status', types.includes('status?:'));
check('API authenticates every request', route.includes('authenticateRequest(request)'));
check('students are denied institution analytics', route.includes("role === 'student'") && route.includes('available only to authorised staff'));
check('platform roles are recognised', route.includes('isPlatformAdmin(role)'));
check('school users are restricted to their organization', route.includes('You cannot view analytics for another school'));
check('teachers are restricted to assigned sections', route.includes('teacher_section_assignments') && route.includes('allowedSectionIds'));
check('teachers are restricted to assigned subjects', route.includes('teacherCanOpenSubject') && route.includes('This subject is not assigned'));
check('class IDs are validated before UUID queries', route.includes('function isUuid') && route.includes('The selected class link is invalid'));
check('pending and active schools are live while suspended schools are excluded', route.includes("neq('status', 'suspended')"));
check('class list uses real academic section UUIDs', route.includes("from('academic_sections')") && route.includes('id: section.id'));
check('student membership is organization scoped', route.includes("from('student_school_memberships')") && route.includes("eq('organization_id', organizationId)"));
check('attempt evidence uses submitted tests only', route.includes("eq('status', 'submitted')"));
check('response evidence joins live question taxonomy', route.includes('paper_questions') && route.includes('subjects') && route.includes('chapters') && route.includes('topics'));
check('all institution API payloads are live', !route.includes("mode: 'demo'") && route.includes("mode: 'live'"));
check('zero-attempt schools retain live records', route.includes('Live school records loaded. No submitted assessment attempts are available yet.'));
check('zero-attempt classes retain live rosters', route.includes('Live class roster loaded. Subject analytics will appear'));
check('workspace shows honest live empty evidence', workspace.includes('Live Evidara data') && workspace.includes('No demonstration records were substituted'));
check('workspace never swaps zero evidence for demo schools', !workspace.includes('hasLiveEvidence ? result :') && !workspace.includes('demonstrationFallback'));
check('student drill-down embeds full analytics workspace', workspace.includes('<AnalyticsV12Workspace mode="school" selectedStudentId={detail.student.id} embedded hideStudentSelector />'));
check('embedded student workspace has all seven analytics views', ['Overview', 'Subjects', 'Chapters', 'Topics', 'Question intelligence', 'Revision priorities', 'Test history'].every((label) => studentAnalytics.includes(label)));
check('embedded school analytics starts from empty live evidence', studentAnalytics.includes('emptyPayload(selectedStudentId'));
check('analytics RPC errors clear stale payloads', studentAnalytics.includes('setPayload(emptyPayload(studentId))'));
check('no real-student benchmark fallback remains', !studentAnalytics.includes('get_v13_benchmark_analytics') && !studentAnalytics.includes('demoPayload'));
check('student analytics uses live evidence RPC', studentAnalytics.includes("rpc('get_student_analytics_v12'"));
check('student embedded navigation has isolated styling', studentCss.includes('.analytics-v12-embedded-nav'));
check('admin school ranking table exists', workspace.includes('School performance analytics') && workspace.includes('Best performing school'));
check('school analytics starts at class list', workspace.includes('ClassesView') && workspace.includes("level === 'school'"));
check('subject and chapter diagnostics remain present', workspace.includes('Chapter performance spread') && workspace.includes('Topic diagnosis'));
check('search, filter and sortable headers remain present', workspace.includes('DataToolbar') && workspace.includes('SortHeader'));
check('class and school downloads remain present', workspace.includes('exportInstitutionReportCards') && workspace.includes('exportInstitutionSchoolReportCards') && workspace.includes('exportInstitutionSchoolResultsCsv'));
check('report downloads do not reveal server secrets', !reports.includes('SUPABASE_SERVICE_ROLE_KEY'));
check('institution CSS remains isolated', institutionCss.includes('.institution-analytics') && institutionCss.includes('.institution-student-full-analytics'));
check('admin analytics view remains registered', store.includes("| 'admin-analytics'") && views.includes("'admin-analytics': 'analytics'"));
check('admin and school sidebars retain analytics routes', sidebar.includes("view: 'admin-analytics'") && sidebar.includes("view: 'school-analytics-overview'"));
check('student analytics remains available to students', page.includes('AnalyticsV12Workspace mode="student"'));
check('question select-all column remains compact', questions.includes('w-[44px] min-w-[44px] max-w-[44px] px-0 text-center'));
check('question serial number column remains fixed', questions.includes('w-[72px] min-w-[72px] max-w-[72px]'));
check('temporary installer payload is excluded from TypeScript', Array.isArray(tsconfig.exclude) && tsconfig.exclude.includes('_institution_analytics_payload'));
check('old institution installer payload is absent after installation', !exists('_institution_analytics_payload'));
check('live-fix installer payload is absent after installation', !exists('_institution_live_fix_payload'));

const failed = checks.filter((item) => !item.ok);
for (const item of checks) console.log(`${item.ok ? '✓' : '✗'} ${item.label}`);
if (failed.length) {
  console.error(`\nInstitution analytics live validation failed (${failed.length}/${checks.length} checks).`);
  process.exit(1);
}
console.log(`\nEvidara live institution analytics checks passed (${checks.length} checks).`);
