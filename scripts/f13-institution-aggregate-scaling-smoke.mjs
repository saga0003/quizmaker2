import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const route = read('src/app/api/institution-analytics/route.ts');
const migration = read('supabase/migrations/20260901142000_phase1_institution_attempt_aggregate_scaling.sql');
const failures = [];
let passed = 0;
const check = (label, condition) => { if (condition) { passed += 1; console.log(`✓ ${label}`); } else { failures.push(label); console.error(`✗ ${label}`); } };
const body = (name, next) => route.slice(route.indexOf(`async function ${name}`), route.indexOf(`async function ${next}`));
const schoolList = body('schoolList', 'schoolClasses');
const schoolClasses = body('schoolClasses', 'programmeSnapshot');
const programme = body('programmeSnapshot', 'gradeSnapshot');
const grade = body('gradeSnapshot', 'classStudents');
const classStudents = body('classStudents', 'responseEvidence');
check('database aggregate RPC is defined', /get_institution_student_attempt_metrics_v1/.test(migration));
check('aggregate RPC is SECURITY INVOKER', /security invoker/i.test(migration));
check('browser roles cannot execute aggregate RPC', /revoke all[\s\S]*from public, anon, authenticated/i.test(migration));
check('only service role receives execute permission', /grant execute[\s\S]*to service_role/i.test(migration));
check('submitted-attempt covering index is defined', /exam_attempts_org_student_submitted_idx/.test(migration));
check('route calls database aggregate in bounded student batches', /get_institution_student_attempt_metrics_v1/.test(route) && /start \+= 500/.test(route));
check('school list no longer downloads raw submitted attempts', !/attemptsForStudents/.test(schoolList) && /attemptMetricsForStudents/.test(schoolList));
check('school class summaries no longer download raw submitted attempts', !/attemptsForStudents/.test(schoolClasses) && /attemptMetricsForStudents/.test(schoolClasses));
check('programme summaries use database aggregates', !/attemptsForStudents/.test(programme) && /attemptMetricsForStudents/.test(programme));
check('grade summaries use database aggregates', !/attemptsForStudents/.test(grade) && /attemptMetricsForStudents/.test(grade));
check('weighted average preserves attempt-level semantics', /percentageSum \/ completedTests/.test(route));
check('question evidence path intentionally keeps raw attempt IDs', /attemptsForStudents/.test(classStudents));
check('server evidence counts sum database aggregate attempt counts', /submittedAttemptCount\(aggregateMetrics\)/.test(route));
if (failures.length) { console.error(`\nF13 aggregate scaling smoke failed: ${failures.length} failed, ${passed} passed.`); process.exit(1); }
console.log(`\nF13 aggregate scaling checks passed (${passed} checks).`);
