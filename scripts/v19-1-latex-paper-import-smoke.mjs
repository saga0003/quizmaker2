import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const exists=(p)=>fs.existsSync(path.join(root,p));
let passed=0,failed=0;
const check=(name,cond)=>{if(cond){passed++;console.log(`PASS ${name}`)}else{failed++;console.error(`FAIL ${name}`)}};
const pkg=JSON.parse(read('package.json'));
const release=read('src/lib/release.ts');
check('package release is 19.1.0',pkg.version==='19.1.0');
check('central release metadata is V19.1',release.includes("19.1.0")&&release.includes('Evidara V19.1'));
check('typecheck hotfix from V19.0.1 is merged',read('src/components/evidara/live-question-bank.tsx').includes('onTaxonomyChanged={async () => { await load(); }}'));
check('NatSciX-style LaTeX paper package parser exists',exists('src/lib/evidaraLatexPaperImport.ts'));
const parser=read('src/lib/evidaraLatexPaperImport.ts');
check('parser supports paper identity headers',parser.includes('"year", "sourceyear"')&&parser.includes('"variant", "phase", "set"')&&parser.includes('"code", "papercode"'));
check('parser supports ZIP image assets',parser.includes('readZip')&&parser.includes('includegraphics')&&parser.includes('uploadQuestionAsset'));
check('parser enforces one paper source per package',parser.includes('imports one paper at a time'));
check('question/option LaTeX fields are produced independently',parser.includes('question_latex: questionLatex')&&parser.includes('option_${letter}_latex'));
check('original question numbering is retained',parser.includes('question_number: questionNumber'));
const dialog=read('src/components/evidara/paper-file-import-dialog.tsx');
check('paper importer accepts LaTeX ZIP packages',dialog.includes('.zip')&&dialog.includes('parseEvidaraLatexPaperPackage'));
check('paper importer creates paper and questions together',dialog.includes("action:'commit'")&&dialog.includes('Create Draft Paper'));
check('duplicate preview is batched safely',dialog.includes('start+=200'));
check('paper import preview renders text, LaTeX and images',dialog.includes('RichQuestionContent')&&dialog.includes('RichOptionContent'));
const rich=read('src/components/evidara/rich-math-content.tsx');
check('mixed inline/display KaTeX renderer exists',rich.includes('MixedMathText')&&rich.includes('InlineMath')&&rich.includes('BlockMath')&&rich.includes('math={normalized}'));
const live=read('src/components/papers/LiveExam.tsx');
const paperPreview=read('src/components/papers/PaperPreview.tsx');
const device=read('src/components/evidara/question-device-preview.tsx');
check('learner exam renders text plus dedicated LaTeX',live.includes('RichQuestionContent')&&live.includes('stem_text')&&live.includes('stem_latex'));
check('paper preview renders rich math content',paperPreview.includes('RichQuestionContent')&&paperPreview.includes('RichOptionContent'));
check('device preview renders rich math content',device.includes('RichQuestionContent')&&device.includes('RichOptionContent'));
check('paper template is bundled',exists('public/templates/Evidara_LaTeX_Paper_Template.tex'));
check('AI conversion prompt is bundled',exists('public/templates/Evidara_AI_QuestionBank_to_LaTeX_Prompt.txt'));
console.log(`\nEvidara V19.1 LaTeX Paper Import: ${passed} passed, ${failed} failed`);
process.exit(failed?1:0);
